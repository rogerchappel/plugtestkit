export function composerJson(metadata) {
  const slug = slugify(metadata.textDomain ?? metadata.name);
  return `${JSON.stringify({
    name: `local/${slug}`,
    description: metadata.description ?? `Test harness for ${metadata.name}`,
    type: 'wordpress-plugin',
    license: metadata.license ?? 'GPL-2.0-or-later',
    require: {},
    requireDev: {
      'phpunit/phpunit': '^9.6',
      'wp-coding-standards/wpcs': '^3.0',
      'dealerdirect/phpcodesniffer-composer-installer': '^1.0'
    },
    scripts: {
      test: 'phpunit',
      lint: 'phpcs'
    }
  }, null, 2)}\n`;
}

export function phpunitXml(metadata) {
  return `<?xml version="1.0"?>
<phpunit bootstrap="tests/bootstrap.php" colors="true">
  <testsuites>
    <testsuite name="${escapeXml(metadata.name)} tests">
      <directory suffix="Test.php">tests</directory>
    </testsuite>
  </testsuites>
</phpunit>
`;
}

export function phpcsXml(metadata) {
  return `<?xml version="1.0"?>
<ruleset name="${escapeXml(metadata.name)}">
  <description>WordPress Coding Standards for ${escapeXml(metadata.name)}.</description>
  <rule ref="WordPress" />
  <file>.</file>
  <exclude-pattern>vendor/*</exclude-pattern>
</ruleset>
`;
}

export function bootstrapPhp(metadata, mainFile) {
  return `<?php
/**
 * PHPUnit bootstrap for ${metadata.name}.
 * Generated by plugtestkit; review paths before committing to production.
 */

$_tests_dir = getenv('WP_TESTS_DIR') ?: '/tmp/wordpress-tests-lib';

if (! file_exists($_tests_dir . '/includes/functions.php')) {
    echo "Could not find WordPress test suite. Set WP_TESTS_DIR.\\n";
    exit(1);
}

require_once $_tests_dir . '/includes/functions.php';

tests_add_filter('muplugins_loaded', function (): void {
    require dirname(__DIR__) . '/${escapePhpSingleQuoted(mainFile)}';
});

require $_tests_dir . '/includes/bootstrap.php';
`;
}

